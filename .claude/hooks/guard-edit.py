#!/usr/bin/env python3
"""PreToolUse hook for Edit/Write/NotebookEdit: protect generated and pinned paths."""
import json
import re
import sys

try:
    payload = json.load(sys.stdin)
except Exception:
    sys.exit(0)

path = (payload.get("tool_input") or {}).get("file_path") or ""
if not path:
    sys.exit(0)

if re.search(r"(^|/)(artifacts|\.dotnet)/", path):
    sys.stderr.write("Blocked: files under artifacts/ and .dotnet/ are generated by the build.\n")
    sys.exit(2)
if re.search(r"(^|/)(global\.json|NuGet\.config)$", path):
    sys.stderr.write("Blocked: global.json and NuGet.config are pinned. Tell the user what you want to change and why, and edit only if they say so.\n")
    sys.exit(2)
sys.exit(0)
